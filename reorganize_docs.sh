# 遊星歯車7段（加算機構）

## 基本式とその意味

```
(Zs・ωs + Zr・ωr) / (Zs + Zr) = ωc
```

これは「歯数比に応じた重みつき平均」を計算する式であり、単純な足し算ではない。テストの重みつき平均（例：期末3倍、中間1倍で(3×80+1×60)/(3+1)=75点）と同じ構造で、遊星歯車では「歯数」がこの「重み」の役割を果たす。

## なぜ固定補正ギアが必要か

当初はZs=Zr（歯数を揃える）で均等な平均にしようとしたが、遊星歯車の構造上、Zr（リングギア）はZs（サンギア）より必ず大きくなる（Zr = Zs + 2Zp）ため、Zs=Zrは物理的に不可能と判明。（リングギアはサンギアを取り囲む外側の輪っかである以上、必ずサンギアより大きい）

このため、サンギア側・リングギア側には常に異なる自動重み（g_s, g_r）がかかる。これを打ち消すため、固定補正ギアを遊星歯車の手前に追加する方針で確定。

## 確定した遊星歯車の仕様

```
Zs(サンギア) = 24歯
Zp(プラネタリギア) = 12歯 × 3個
Zr(リングギア) = 48歯
```

※遊星歯車自体はm=1.0基準で確定したが、重み・入力ユニット側(m=0.5)との接続部はCAD化時にスケールを揃える必要がある（未確定事項、[../07-open-questions.md](../07-open-questions.md) 参照）。

**組み立て条件の確認：**

```
条件1(かみ合い): Zr = Zs + 2×Zp → 48 = 24+2×12 ✓
条件2(等間隔配置): (Zs+Zr)/プラネタリ数 = (24+48)/3 = 24(整数) ✓
```

## 固定補正ギアの値

```
g_s(サンギア側の自動重み) = 24/(24+48) = 0.333
g_r(リングギア側の自動重み) = 48/(24+48) = 0.667

これを打ち消す固定補正ギア:
  サンギア側入力 → ×3固定補正ギア
  リングギア側入力 → ×1.5固定補正ギア
```

## 全段7段で同じ歯車セットを使い回せる

段1～4（8入力→4出力）で使った歯数セット（Zs=24, Zp=12×3, Zr=48）と同じ固定補正ギア（×3、×1.5）は、段5～7（4→2→1の集約）でもそのまま使い回せることが確認できた。固定補正ギアは「遊星歯車自体の歯数比による自動重み」を打ち消すためのものなので、歯数自体を変えない限り、何段目でも同じ補正倍率で対応できる。

## 確定した全体構造

```
特徴量8個(edge_0_0, edge_0_2, edge_2_1, B_2_2, edge_2_3, edge_2_4, edge_4_1, G_4_2)
      ↓ 重み用歯車（固定）+ 入力用ユニット（16段階）で値を設定
      ↓
【段1～4】 8入力 → 4出力(A, B, C, D)
  段1: (入力1, 入力2) → A
  段2: (入力3, 入力4) → B
  段3: (入力5, 入力6) → C
  段4: (入力7, 入力8) → D
      ↓
【段5～6】 4入力 → 2出力(E, F)
  段5: (A, B) → E
  段6: (C, D) → F
      ↓
【段7】 2入力 → 1出力
  段7: (E, F) → 最終出力
      ↓
閾値判定機構へ
```

## 必要な部品（全7段共通、種類は少ない）

| 部品 | 仕様 | 必要数 |
| --- | --- | --- |
| サンギア | 24歯 | 7個 |
| プラネタリギア | 12歯 | 21個(3個×7段) |
| リングギア | 48歯 | 7個 |
| 固定補正ギア(×3用、サンギア側) | - | 7個 |
| 固定補正ギア(×1.5用、リングギア側) | - | 7個 |

**設計上のメリット**：1種類の遊星歯車ユニットをCADで設計すれば、それを7回複製するだけで全体が完成する。

