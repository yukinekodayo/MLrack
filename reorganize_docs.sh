# 特徴量・データセット・学習モデル

## なぜデータで検証したか

当初は「耳の高さ比」など人間の直感で特徴量を選ぶ予定だったが、勘で決めず実データで検証する方針に変更した。

## データセットの検証履歴

| データセット | 内容 | 結果 |
| --- | --- | --- |
| dogsvscats-master（GitHub経由） | 全身・背景あり、25000枚 | 分離度ほぼゼロ。使い物にならない |
| TensorFlow Datasets cats_vs_dogs | 上記と同一出典（Asirra CAPTCHA） | 同等と判断し未検証 |
| Oxford-IIIT Pet Dataset（顔切り出し） | XMLバウンディングボックスで顔を切り出し、猫1181枚・犬2490枚 | 分離度が改善。以後の主力データ |
| fferlito（猫）+ DogFaceNet（犬） | 別ソースの位置合わせ済み顔 | 64%で悪化。不採用（データ出どころの不一致が影響したと推測） |

**採用データセット：Oxford-IIIT Pet Dataset**（GitHub `ml4py/dataset-iiit-pet` 経由で取得、顔切り出し済み）

## 特徴量の種類ごとの精度検証

| 特徴量の種類 | 特徴量数 | 精度（バランス済みデータで5-fold CV） |
| --- | --- | --- |
| 全身画像・画像全体のざっくり統計（上下輝度比、対称性など） | 5個 | ほぼ差なし |
| 顔画像・画像全体のざっくり統計 | 5個 | 弱い改善のみ |
| 顔画像・位置別（3×3グリッド）エッジ密度（CNN発想） | 6～9個 | 約68～69% |
| 顔画像・位置別（5×5グリッド）エッジ密度＋RGB色情報 | 最大100個 | 76%で頭打ち |
| **最適選択8特徴量**（SelectKBestで上位25候補→CVでランダム探索） | 8個 | **71.0～71.6%（採用）** |

グリッドを細かくしても100特徴量で76%が頭打ちになることが確認され、「エッジ密度＋色情報、線形分類器」という枠組み自体の限界と判断。「電気を一部使う（電子加算回路追加）」「もっとグリッドを細かくする」等も検討したが、2人・3ヶ月という制約を踏まえ71%前後を現実的な上限として受け入れた。

## 特徴量抽出の手順

1. 顔の切り出し：XMLのバウンディングボックス情報を使用（余白15%）
2. 画像をリサイズ後、5×5グリッドに分割
3. 各セルごとに、Canny法によるエッジ密度、R・G・B各チャンネル平均を計算（計100特徴量候補）
4. SelectKBest（f_classif）で上位25候補に絞り込み
5. 上位25候補から5-foldクロスバリデーションで最良の8組み合わせを2000通りランダム探索
6. 分類器：ロジスティック回帰（線形分類器。歯車の「重み付き和」に対応）
7. 猫・犬の枚数はアンダーサンプリングでバランスさせて検証

Google Colabで再現可能：[`assets/colab_weight_calculation.ipynb`](../assets/colab_weight_calculation.ipynb)（特徴量抽出～重み計算まで全自動）

