| ±4.000 | 144歯 |
| ±3.467 | 125歯 |
| ±2.933 | 106歯 |
| ±2.400 | 86歯 |
| ±1.867 | 67歯 |
| ±1.333 | 48歯 |
| ±0.800 | 29歯 |
| ±0.267 | 17歯 |

歯数一覧：**17, 29, 48, 67, 86, 106, 125, 144**（重みユニットと共通規格、部品共通化可能）

