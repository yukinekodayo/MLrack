# 重み付けユニット（完全固定式・電子制御なし）

## 構造（1特徴量あたり）

```
[重み用歯車1枚(固定)] → [アイドラーギア(正負、固定)] → 固定補正ギアへ
```

モータ・スリーブ・切替機構は一切不要。組立時に歯数を選んで固定するだけ。

## モジュール・基準歯の確定

初期（基準歯24歯、m=1.0）では最小6歯などアンダーカット（歯の根元が削れて弱くなる現象）の基準（17歯未満）を下回ることが判明したため、基準歯を**72歯**に変更。さらに直径を現実的なサイズ（最大72mm以内）に収めるため、**モジュール0.5**に確定（候補：0.3は加工難、1.0は大きすぎる）。

```
基準歯: 72歯（直径36mm、m=0.5）
最小歯数下限: 17歯（アンダーカット回避）
```

## 歯数への変換方法

重み係数をそのまま歯数にはできないため、以下の手順で正規化する。

1. 8つの重みのうち絶対値が最大のもの（edge_0_2 = 0.7449）を基準に、各重みを**0〜2倍**の範囲に正規化する：`normalized = |重み| ÷ 0.7449 × 2.0`
2. 正規化した値に基準歯72歯を掛けて歯数にする：`歯数 = round(72 × normalized)`
3. アンダーカット回避のため、17歯を下回る場合は17歯にする

まとめると：

```
歯数 = max(round(72 × (|重み| ÷ 0.7449) × 2.0), 17)
     = max(round(144 × |重み| ÷ 0.7449), 17)
```

> ❗**訂正**：旧ドキュメントでは、この式に誤って `÷ 2.0` が追加されており（`× 2.0 ÷ 2.0`）、「実質的には `round(72 × |重み| ÷ 0.7449)`」と簡略化されていましたが、これは計算式の誤りです。実際に下表の歯数はすべて `×2.0` を生かした式（`round(144 × |重み| ÷ 0.7449)`）で計算されており、基準歯72歯の**2倍（144歯・直径72mm）が最大歯数**になっています（「直径最大72mm以内」という設計制約とも整合しています）。下表の歯数の値そのものは元から正しいため、変更していません。

